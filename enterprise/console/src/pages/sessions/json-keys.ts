/** 「中文(英文)」；查不到就只给英文。 */
export function labelOfKey(key: string): string {
  const zh = KEY_LABEL[key];
  return zh ? `${zh}(${key})` : key;
}

export function hasKeyLabel(key: string): boolean {
  return key in KEY_LABEL;
}
