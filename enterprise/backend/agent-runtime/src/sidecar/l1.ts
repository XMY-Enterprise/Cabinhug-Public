/**
 * 组装消息。句与句之间的连贯性由这里保证。
 *
 * # 已说过的句子以 `assistant` 身份回填，而不是列进 prompt
 *
 * 写成「刚才已经说过这些，换个角度：- xxx」这样的黑名单时，
 * 生成的句子各自重新起头、互不衔接。"别重复"和"接着说"是两件事：
 * 前者只约束不许一样，不要求后一句与前一句有关系。
 *
 * 把自己说过的话当成真实的对话轮次回填后，模型面对的是
 * "我刚说了这句，现在轮到我接"，连贯性来自它自己的上文。
 *
 * # 后续轮的 user 消息是一句"嗯"
 *
 * 它只是占位：对话结构要求 user/assistant 交替。写成实质内容（如"再说说吃的"）
 * 等于替车主指定话题，而车主此刻没有在说话。
 */
export function guideMessages(input: {
  place?: string;
  nowText: string;
  said: readonly string[];
}): GuideMessage[] {
  const opening = [
    // 日期用于判断"什么当季"。只写「现在是八月」时模型会从天气起头，
    // 而天气不在话题里，所以附带限定。
    `现在是${input.nowText}，这个只用来想什么当季，别聊天气。`,
    input.place ? `车主话里提到的地方：${input.place}` : "车主话里没有提到任何地方。",
    "",
    "说一句。",
  ].join("\n");

  const msgs: GuideMessage[] = [{ role: "user", content: opening }];
  /*
   * 回填几句：够它记得自己已经聊到哪儿了。
   *
   * 只回填 3 句时，后面的句子会绕回已经看不见的早先话题。
   * 一轮最多六七句、每句 30 字以内，全部回填的上下文成本可以忽略。
   */
  for (const s of input.said.slice(-RECALL)) {
    msgs.push({ role: "assistant", content: s });
    msgs.push({ role: "user", content: "嗯。" });
  }
  return msgs;
}

/** 回填几句上文。取值理由见 `guideMessages`。 */
const RECALL = 8;

/** 第 1 句的长度上限（进度前缀 23 字 + 闲话）；后续句用 `TAIL_MAX_CHARS`。 */
export const FIRST_MAX_CHARS = 60;

/**
 * 闲话本身的长度闸。
 *
 * 提示词里要的是 25 字，这里放到 36，闸比要求松：
 * 卡在 30 时实测 3/30 句因 31~34 字被拒，被拒的往往是展开得最好的句子，
 * 拒了就回落成 L0 模板话。
 * 36 字 × 200ms/字 ≈ 7.2 秒，仍在端上等待上限（12 秒）之内。
 */
export const TAIL_MAX_CHARS = 36;

/**
 * 后置过滤。能抓的在这里抓，抓不住的靠输入限制与喂日期（见上）。
 *
 * 返回拒绝原因；`undefined` 表示放行。拒绝即回落 L0。
 */
export function rejectGuideText(
  text: string,
  maxChars = TAIL_MAX_CHARS,
  /** 没有地名时更严：连车的事也不许沾（见 `GUIDE_SYSTEM`）。 */
  noVehicle = false,
): string | undefined {
  const t = text.trim();
  if (!t) return "空";
  if ([...t].length > maxChars) return `超长(${[...t].length}字)`;
  // 数字类：年份、距离、海拔、门票——导游最容易编的就是这些
  if (/\d/.test(t)) return "出现数字";
  /*
   * 中文数量。先摘掉口语里的固定说法：「一年到头」「一年四季」不是数量断言，
   * 不摘会被误杀（如"那边一年到头绿油油的"），误杀即静默回落 L0。
   */
  const bare = t.replace(/一年(到头|四季)|三三两两|三言两语|一五一十/g, "");
  if (/[一二三四五六七八九十百千万]{1,}(年|里|米|度|块|家|个世纪)/.test(bare)) return "出现数量";
  if (/(唐|宋|元|明|清|汉|民国)(代|朝)/.test(t)) return "编朝代";
  if (/(值得|一定要|推荐|建议|不妨|可以去)/.test(t)) return "推荐口气";
  if (/[？?]\s*$/.test(t)) return "反问";
  /*
   * 舞台提示与标记，如「（顿了顿）说着说着，倒想起…」。必须在服务端挡住：
   * 下游是 TTS，会把"顿了顿"念出来。
   */
  if (/[（(【\[*＊][^）)】\]*＊]*[）)】\]*＊]/.test(t)) return "带括号或标记";
  /*
   * 车的事不归它说（红线：旁路不作答）。
   * 有地名时不查这条：「街上的人跑得比车还快」这种比喻无害；
   * 没地名时模型容易滑到"空调得开足点""最怕堵在路上"，那已经是在给用车建议。
   */
  if (noVehicle && /(车|空调|油耗|续航|堵|路况|方向盘|导航)/.test(t)) return "绕回车上";
  return undefined;
}

/** `2026年8月`。喂给模型用。 */
export function nowText(at: number): string {
  const d = new Date(at);
  return `${d.getFullYear()}年${d.getMonth() + 1}月`;
}
