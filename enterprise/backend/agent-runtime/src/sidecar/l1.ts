/**
 * L1 导游式闲聊。
 *
 * # 只给地名，不给问题原文
 *
 * 让模型看着用户的问题去闲聊时，它会回答那个问题（续航、路线、天气），
 * 加禁令也压不住（实测犯规率约 40%）。只给地名、不给问题原文时，
 * 实测过滤器零命中、人工复核未见编造具体事实：它谈的不是用户问的那件事，
 * "回答问题"在结构上不存在。
 *
 * # 话题只有三样：吃的、老故事、好看的地方
 *
 * 写成"你只记得这三样"，不写成"你只准聊这三样"：前者是模型对自身处境的认知，
 * 后者是容易被绕过的禁令。
 *
 * "聊历史"与"不许出现朝代与数字"之间的张力是刻意保留的：历史最容易编年份，
 * 且用户无从证伪。所以人设写的是"聊那份年头久的感觉，别去报是哪年哪代"，
 * 只说氛围，不说考据。
 *
 * # 本模块没有模型调用
 *
 * `check:arch` 的 `sidecar-isolation` 禁止 `sidecar/` import `../llm`：
 * 能力边界靠依赖守，不靠提示词。这里只定义接口与提示词，实现由 `index.ts` 在装配层注入。
 */

/** 生成一句闲话。实现由装配层注入（见模块注释）。 */
export type FillerWriter = (input: {
  /** 归账用（成本口径）：这句闲话烧的 token 记到哪个会话/轮次名下。 */
  sessionId: string;
  turnId: string;
  /** 用户话里提到的地方；取不到就不传，模型会说一句不带地点的闲话。 */
  place?: string;
  /** 现在是什么时候，形如 `2026年8月`。必须传，见 `guideMessages` 的说明。 */
  nowText: string;
  /**
   * 本轮自己已经说过的句子，按顺序。
   *
   * 它是上文，不是"别重复这些"的黑名单。见 `guideMessages` 的说明。
   */
  said: readonly string[];
}) => Promise<string | undefined>;

/** 一条对话消息。故意只声明这么点，不引 `../llm` 的类型（`sidecar-isolation`）。 */
export interface GuideMessage {
  role: "user" | "assistant";
  content: string;
}

