/**
 * general 路由的作答范围说明：与车无关的代工请求（如写代码）不接。
 *
 * # 不在护栏里
 *
 * 这类请求不违规、不是注入、不碰车辆安全，缺的是业务范围而不是安全边界。
 * 放进护栏会让控制台的「拦截数」混入非安全类拦截。
 *
 * # 不写进 `supervisor.md`
 *
 * 那份提示词同时是意图那一跳的系统提示词（`supervisor-intent` 剥后缀后就是 `supervisor`），
 * 加入"哪些不接"可能让路由漂移，表现为答非所问而不是报错。因此挂在 `answerNode` 的本轮尾区里，
 * 且只在落到 general 时挂，其余路由的提示词不变。
 *
 * # 只点名、不兜底
 *
 * 拒错的代价不对称：离线正则下「我这车空调制冷不行」会落 general（见 route.ts 头注），
 * 把真实的用车求助婉拒掉比多答一次代工请求更糟。
 * 所以只列几类容易识别的代工请求，其余一律照常答，拿不准也答。
 *
 * 当前实现依赖 LLM 遵守，效果是概率性的。结构化版本
 * （意图层出 scope 字段 → 编排层走固定话术节点，不调模型）尚未实现。
 */

/** 回滚口：`CABINHUG_GENERAL_SCOPE=off` 时尾区不附加作答范围说明。 */
export function generalScopeEnabled(env: NodeJS.ProcessEnv = process.env): boolean {
  return (env.CABINHUG_GENERAL_SCOPE ?? "on") !== "off";
}

