/**
 * 造数素材：五场景的口语模板。
 *
 * # 像 ASR 转写，不像书面语
 *
 * 标点齐整、结构清楚的句子会让 Coder 编码又快又一致，一致率因此高估真实语料上的可靠性。
 * 真实的输入来自车里说的话：没有标点、有口水词、偶尔识别错一两个字。
 * 所以模板刻意不写标点、掺口水词，并留一批"识别错"的变体。
 *
 * # 不调 LLM 生成
 *
 * 可复现性优先。同一个种子两次生成的语料必须逐字节相同，
 * gold set 标过的 200 条才能在重新造数后对上。
 *
 * # 反例句是刻意的
 *
 * 每个场景约 10% 是"其实比我想的好"这类。主题必须保留反例成员：
 * 只存支持成员的主题在任何一张图上都显得证据充分（见 `research_themes` 的说明）。
 * 没有反例语料，Challenger 无从找起。
 */

